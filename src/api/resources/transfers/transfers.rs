    ///     };
    ///     let client = Whop::new(config).expect("Failed to build client");
    ///     client
    ///         .transfers
    ///         .list(
    ///             &TransfersListQueryRequest {
    ///                 ..Default::default()
    ///             },
    ///             None,
    ///         )
    ///         .await;
    /// }
    /// ```
